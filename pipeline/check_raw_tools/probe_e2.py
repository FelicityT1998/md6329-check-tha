import sys, pandas as pd
t0 = pd.read_csv(sys.argv[1], sep="\t", low_memory=False)
h = pd.read_csv(sys.argv[2]); img = pd.read_csv(sys.argv[3])
m = t0.T0_HEXOL.isna(); mp = t0.T0_HEXOPIJNL.isna()
print("HEXO ROM missing by hip pain", t0.groupby("T0_JVHPIJN").T0_HEXOL.apply(lambda s: round(s.isna().mean(), 3)).to_dict())
print("by group", t0.groupby("T0_JVCON").T0_HEXOL.apply(lambda s: round(s.isna().mean(), 3)).to_dict())
fmt = img.groupby("nsin").fmt.first(); t0["fmt"] = t0.nsin.map(fmt)
print("by image format", t0.groupby("fmt", dropna=False).T0_HEXOL.apply(lambda s: round(s.isna().mean(), 3)).to_dict())
print("ROM missing x pain missing", pd.crosstab(m, mp).to_dict())
print("missing pattern same subject for HEXO/HADD/HABD ROM", int((t0[["T0_HEXOL","T0_HADDL","T0_HABDL"]].isna().sum(axis=1).isin([0,3])).sum()), "/", len(t0))
e = h.groupby("nsin").event.max(); t0["ev"] = t0.nsin.map(e)
print("subject event rate by HEXO missing", t0.groupby(m).ev.mean().round(3).to_dict())
# sorted by nsin? check whether missingness clusters in id order (time/centre proxy)
s = t0.sort_values("nsin"); q = pd.qcut(s.nsin.rank(), 10, labels=False)
print("missing by nsin decile", s.groupby(q).T0_HEXOL.apply(lambda x: round(x.isna().mean(), 2)).to_list())
print("missing by DICOM StudyDate year", t0.assign(y=t0.nsin.map(img[img.fmt=='dcm'].groupby('nsin').StudyDate.first().astype(str).str[:4])).groupby('y').T0_HEXOL.apply(lambda x: round(x.isna().mean(), 2)).to_dict())
